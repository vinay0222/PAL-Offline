package com.idreameducation.ipreppal.roomdatabase.model;

import androidx.room.ColumnInfo;
import androidx.room.Entity;
import androidx.room.PrimaryKey;

import java.io.Serializable;

@Entity
public class ReportsTopicWisePracticeModel implements Serializable {

    @PrimaryKey(autoGenerate = true)
    private int id;
    @ColumnInfo(name = "user_id")
    private String userId;
    @ColumnInfo(name = "board")
    private String board;
    @ColumnInfo(name = "sClass")
    private String sClass;
    @ColumnInfo(name = "subject")
    private String subject;
    @ColumnInfo(name = "type")
    private String type;
    @ColumnInfo(name = "date")
    private String date;
    @ColumnInfo(name = "time")
    private long time;
    @ColumnInfo(name = "topic_id")
    private String topicId;
    @ColumnInfo(name = "name")
    private String name;
    @ColumnInfo(name = "current_level")
    private String currentLevel;
    @ColumnInfo(name = "p_date")
    private String pDate;
    @ColumnInfo(name = "mastery")
    private String mastery;
    @ColumnInfo(name = "streak_progress")
    private String streakProgress;
    @ColumnInfo(name = "topic_name")
    private String topicName;
    @ColumnInfo(name = "lang")
    private String lang;
    @ColumnInfo(name = "subjectName")
    private String subjectName;

    public String getSubjectName() {
        return subjectName;
    }

    public void setSubjectName(String subjectName) {
        this.subjectName = subjectName;
    }

    public String getLang() {
        return lang;
    }

    public void setLang(String lang) {
        this.lang = lang;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getUserId() {
        return userId;
    }

    public void setUserId(String userId) {
        this.userId = userId;
    }

    public String getBoard() {
        return board;
    }

    public void setBoard(String board) {
        this.board = board;
    }

    public String getSClass() {
        return sClass;
    }

    public void setSClass(String sClass) {
        this.sClass = sClass;
    }

    public String getSubject() {
        return subject;
    }

    public void setSubject(String subject) {
        this.subject = subject;
    }

    public String getType() {
        return type;
    }

    public void setType(String type) {
        this.type = type;
    }

    public String getDate() {
        return date;
    }

    public void setDate(String date) {
        this.date = date;
    }

    public long getTime() {
        return time;
    }

    public void setTime(long time) {
        this.time = time;
    }

    public String getTopicId() {
        return topicId;
    }

    public void setTopicId(String topicId) {
        this.topicId = topicId;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getCurrentLevel() {
        return currentLevel;
    }

    public void setCurrentLevel(String currentLevel) {
        this.currentLevel = currentLevel;
    }

    public String getPDate() {
        return pDate;
    }

    public void setPDate(String pDate) {
        this.pDate = pDate;
    }

    public String getMastery() {
        return mastery;
    }

    public void setMastery(String mastery) {
        this.mastery = mastery;
    }

    public String getStreakProgress() {
        return streakProgress;
    }

    public void setStreakProgress(String streakProgress) {
        this.streakProgress = streakProgress;
    }

    public String getTopicName() {
        return topicName;
    }

    public void setTopicName(String topicName) {
        this.topicName = topicName;
    }
}